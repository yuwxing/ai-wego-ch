  moments.push({
    type: 'phase', text: '上课 20分钟 · 最难熬的时段', tag: '后半段',
  })
  for (let i = 0; i < 5; i++) {
    const atmo = pick(ATMOSPHERE_LINES['后半段'])
    moments.push({ type: 'narrator', text: atmo, tag: '后半段' })
    if (Math.random() > 0.4) {
      const mb = pick(MICRO_BEHAVIORS)
      moments.push({ type: 'micro', text: mb.text, tag: `✦ ${mb.pos}` })
    }
    if (Math.random() > 0.5) {
      moments.push({ type: 'teacher', text: pick(TEACHER_LINES), tag: '老师' })
    }
    if (Math.random() > 0.5) {
      moments.push({ type: 'whisper', text: pick(WHISPER_LINES), tag: '窸窣声' })
    }
    if (Math.random() > 0.6) {
      moments.push({ type: 'memory', text: pick(MEMORY_HOOKS), tag: '💭 回忆碎片' })
    }
  }

  // attention check end
