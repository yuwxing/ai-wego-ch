  const moments: Moment[] = []
  const subject = pick(['语文','数学','英语','物理','化学','历史','地理','生物'])
  const totalMin = 40

  // ===== 课前 =====
  moments.push({
    type: 'phase', text: `📖 ${subject}课 · 第3节\n课前 · 距离上课还有2分钟`,
    tag: '课外',
  })
  pickN(ATMOSPHERE_LINES['课前'], 2, 1).forEach(t => {
    moments.push({ type: 'narrator', text: t, tag: '课前' })
  })

  // ===== 上课 =====
