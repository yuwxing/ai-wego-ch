function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)]
}

function pickN<T>(arr: T[], n: number, min?: number): T[] {
  const shuffled = [...arr].sort(() => Math.random() - 0.5)
  const count = Math.max(min ?? 1, Math.min(n, arr.length))
  return shuffled.slice(0, count)
}

function genAttention(): AttentionSnapshot {
  return {
    following: Math.floor(18 + Math.random() * 8),
    half: Math.floor(10 + Math.random() * 8),
    drifting: Math.floor(3 + Math.random() * 6),
    disconnected: Math.floor(1 + Math.random() * 4),
  }
}

function sum(a: AttentionSnapshot): number {
  return a.following + a.half + a.drifting + a.disconnected
}

