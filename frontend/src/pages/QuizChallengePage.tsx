function pickQuestions(bank: Question[], count = 15): Question[] {
  const shuffled = shuffle(bank)
  return shuffled.slice(0, count)
}

async function generateQuestionsByAI(type: string): Promise<Question[] | null> {
  const apiKey = localStorage.getItem('deepseek_api_key') || localStorage.getItem('deepseek-api-key')
  if (!apiKey) return null

  const topics: Record<string, string> = {
    poetry: '中国古诗词（中小学必背篇目及经典名句，上下句填空）',
    history: '中国历史和世界历史常识',
    science: '跨学科科学常识（物理、化学、生物、天文、地球科学）',
    geography: '世界地理和中国地理常识',
  }

  const prompt = `你是一个专业出题老师。请生成 15 道关于"${topics[type] || type}"的单项选择题，每道题 4 个选项，难度中等，不重复。

要求：正确答案必须随机分布在 A/B/C/D 四个位置，不能全部集中在同一个选项！

请严格按照以下 JSON 格式输出，不要包含任何其他文字：
{
  "questions": [
    {
      "q": "题目内容",
      "opts": ["A选项", "B选项", "C选项", "D选项"],
      "answer": 0
    }
  ]
}
注意：answer 字段是正确答案的索引（0=A, 1=B, 2=C, 3=D），必须随机分布 0~3 之间。题目不能重复，确保每道题都有唯一正确答案。`

  try {
    const res = await fetch('https://api.deepseek.com/v1/chat/completions', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Authorization': `Bearer ${apiKey}` },
      body: JSON.stringify({ model: 'deepseek-v4-flash', messages: [{ role: 'system', content: '你是一个专业的出题老师，只输出 JSON。' }, { role: 'user', content: prompt }], max_tokens: 2048, temperature: 0.8 }),
    })
    if (!res.ok) return null
    const data = await res.json()
    const text = data.choices?.[0]?.message?.content || ''
    const jsonMatch = text.match(/\{[\s\S]*\}/)
    if (!jsonMatch) return null
    const parsed = JSON.parse(jsonMatch[0])
    if (!parsed.questions || !Array.isArray(parsed.questions) || parsed.questions.length === 0) return null
    return parsed.questions.slice(0, 15).map((q: any) => {
      const opts = Array.isArray(q.opts) && q.opts.length === 4 ? [...q.opts] : ['A', 'B', 'C', 'D']
      let answer = typeof q.answer === 'number' && q.answer >= 0 && q.answer <= 3 ? q.answer : 0
      // Randomize answer position by moving correct answer to a random slot
      const correctText = opts[answer]
      const wrong = opts.filter((_: any, i: number) => i !== answer)
      const newPos = Math.floor(Math.random() * 4)
      wrong.splice(newPos, 0, correctText)
      return { q: q.q, opts: wrong, answer: newPos }
    })
  } catch {
    return null
  }
}

